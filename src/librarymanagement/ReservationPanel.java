    private void btnCancelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelActionPerformed
        int id = Utils.getSelectedId(tblReservations);
        if (id == -1) {
            Utils.showWarning(this, "Hãy chọn một lượt đặt trước trong bảng.");
            return;
        }
        if (!Utils.confirm(this, "Hủy lượt đặt trước này?")) {
            return;
        }
        try {
            // If a copy was being kept for this reader, put it back on the shelf
            Object copyId = DBConnection.scalar("SELECT held_copy_id FROM reservations WHERE reservation_id = ? "
                    + "AND status = 'READY'", id);
            int rows = DBConnection.update("UPDATE reservations SET status = 'CANCELLED' WHERE reservation_id = ? "
                    + "AND status IN ('WAITING', 'READY')", id);
            if (rows == 0) {
                Utils.showWarning(this, "Lượt đặt trước này đã kết thúc rồi.");
            } else if (copyId != null) {
                DBConnection.update("UPDATE book_copies SET status = 'AVAILABLE' WHERE copy_id = ? AND status = 'ON_HOLD'", copyId);
                Utils.showInfo(this, "Đã hủy. Hãy đưa bản sách đang giữ trở lại kệ.");
            }
            loadBooks();
            loadReservations();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnCancelActionPerformed

    private void btnReloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReloadActionPerformed
        try {
            int expired = LoanService.expireOldHolds();
            if (expired > 0) {
                Utils.showInfo(this, expired + " lượt đặt trước đã quá hạn nhận sách và đã được hủy.");
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
        loadBooks();
        loadReservations();
    }//GEN-LAST:event_btnReloadActionPerformed

    /** Only titles with no copy on the shelf can be reserved. */
    private void loadBooks() {
        try {
            Utils.fillCombo(cboBook, "SELECT b.book_id, b.title FROM books b "
                    + "WHERE b.is_deleted = 0 AND b.is_reference = 0 "
                    + "AND EXISTS (SELECT 1 FROM book_copies x WHERE x.book_id = b.book_id AND x.status IN ('ON_LOAN', 'ON_HOLD')) "
                    + "AND NOT EXISTS (SELECT 1 FROM book_copies x WHERE x.book_id = b.book_id AND x.status = 'AVAILABLE') "
                    + "ORDER BY b.title", null);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void loadReservations() {
        String where = "";
        if (cboShow.getSelectedIndex() == 0) {
            where = "WHERE rv.status IN ('WAITING', 'READY') ";
        }
        String sql = "SELECT rv.reservation_id AS 'ID', r.card_no AS 'Mã thẻ', r.full_name AS 'Họ tên', "
                + "b.title AS 'Tên sách', "
                + "CASE rv.status WHEN 'WAITING' THEN 'Đang chờ' WHEN 'READY' THEN 'Sẵn sàng - chờ nhận' "
                + "  WHEN 'FULFILLED' THEN 'Đã nhận' WHEN 'CANCELLED' THEN 'Đã hủy' ELSE 'Quá hạn nhận' END AS 'Trạng thái', "
                + "bc.barcode AS 'Bản sách đang giữ', "
                + "DATE_FORMAT(rv.created_at, '%d/%m/%Y %H:%i') AS 'Ngày đặt', "
                + "DATE_FORMAT(rv.expires_at, '%d/%m/%Y %H:%i') AS 'Hạn nhận sách' "
                + "FROM reservations rv "
                + "JOIN readers r ON r.reader_id = rv.reader_id "
                + "JOIN books b ON b.book_id = rv.book_id "
                + "LEFT JOIN book_copies bc ON bc.copy_id = rv.held_copy_id "
                + where
                + "ORDER BY rv.created_at";
        try {
            Utils.loadTable(tblReservations, sql);
            Utils.hideColumn(tblReservations, 0);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

