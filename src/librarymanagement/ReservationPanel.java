    private void btnReserveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReserveActionPerformed
        String cardNo = txtCardNo.getText().trim().toUpperCase();
        Integer bookId = Utils.getComboId(cboBook);
        if (cardNo.isEmpty()) {
            Utils.showWarning(this, "Vui lòng nhập mã thẻ độc giả.");
            txtCardNo.requestFocus();
            return;
        }
        if (bookId == null) {
            Utils.showWarning(this, "Không có đầu sách nào đã hết bản để đặt trước.");
            return;
        }
        try {
            Object readerId = DBConnection.scalar("SELECT reader_id FROM readers WHERE card_no = ?", cardNo);
            if (readerId == null) {
                Utils.showWarning(this, "Không tìm thấy độc giả có mã thẻ " + cardNo + ".");
                return;
            }
            LoanService.reserve(((Number) readerId).intValue(), bookId);
            Utils.showInfo(this, "Đã đặt trước. Khi có người trả sách, sách sẽ được giữ cho độc giả này.");
            txtCardNo.setText("");
            loadReservations();
        } catch (LoanService.LoanException ex) {
            Utils.showWarning(this, ex.getMessage());
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnReserveActionPerformed

