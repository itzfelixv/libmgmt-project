    private void loadCombos() {
        try {
            Utils.fillCombo(cboType, "SELECT type_id, name FROM reader_types ORDER BY type_id", null);
            Utils.fillCombo(cboFaculty, "SELECT faculty_id, name FROM faculties ORDER BY name", "(Không)");
            Utils.fillCombo(cboClass, "SELECT class_id, code FROM classes ORDER BY code", "(Không)");

            // Remember which faculty each class belongs to
            classFaculty.clear();
            Connection c = DBConnection.getConn();
            try {
                ResultSet rs = c.prepareStatement("SELECT class_id, faculty_id FROM classes").executeQuery();
                while (rs.next()) {
                    classFaculty.put(rs.getInt(1), rs.getInt(2));
                }
            } finally {
                c.close();
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void loadReaders() {
        String sql = "SELECT r.reader_id AS 'ID', r.card_no AS 'Mã thẻ', r.full_name AS 'Họ tên', t.name AS 'Loại', "
                + "CASE r.gender WHEN 'M' THEN 'Nam' WHEN 'F' THEN 'Nữ' ELSE 'Khác' END AS 'Giới tính', "
                + "r.dob AS 'Ngày sinh', r.phone AS 'Điện thoại', r.email AS 'Email', "
                + "COALESCE(f.name, cf.name) AS 'Khoa', c.code AS 'Lớp', r.card_expiry AS 'Hạn thẻ', "
                + "CASE WHEN r.status = 'ACTIVE' AND r.card_expiry < CURDATE() THEN 'Hết hạn' "
                + "     WHEN r.status = 'ACTIVE' THEN 'Hoạt động' "
                + "     WHEN r.status = 'SUSPENDED' THEN 'Tạm khóa' "
                + "     WHEN r.status = 'GRADUATED' THEN 'Đã tốt nghiệp' ELSE 'Ngừng' END AS 'Trạng thái' "
                + "FROM readers r "
                + "JOIN reader_types t ON t.type_id = r.type_id "
                + "LEFT JOIN classes c ON c.class_id = r.class_id "
                + "LEFT JOIN faculties f ON f.faculty_id = r.faculty_id "
                + "LEFT JOIN faculties cf ON cf.faculty_id = c.faculty_id "
                + "ORDER BY r.card_no";
        try {
            Utils.loadTable(tblReaders, sql);
            Utils.hideColumn(tblReaders, 0);
            search();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void search() {
        int searchBy = cboSearchBy.getSelectedIndex();
        switch (searchBy) {
            case 1 -> Utils.filterTable(tblReaders, txtSearch.getText(), COL_CARD);
            case 2 -> Utils.filterTable(tblReaders, txtSearch.getText(), COL_NAME);
            case 3 -> Utils.filterTable(tblReaders, txtSearch.getText(), COL_CLASS);
            case 4 -> Utils.filterTable(tblReaders, txtSearch.getText(), COL_FACULTY);
            default -> Utils.filterTable(tblReaders, txtSearch.getText());
        }
        lblCount.setText(tblReaders.getRowCount() + " độc giả");
    }

    /** Loads the selected reader into the form. */
    private void showSelectedReader() {
        int id = Utils.getSelectedId(tblReaders);
        if (id == -1) {
            return;
        }
        try {
            Connection c = DBConnection.getConn();
            try {
                PreparedStatement ps = c.prepareStatement("SELECT * FROM readers WHERE reader_id = ?");
                ps.setInt(1, id);
                ResultSet rs = ps.executeQuery();
                if (rs.next()) {
                    selectedId = id;
                    txtCardNo.setText(rs.getString("card_no"));
                    txtFullName.setText(rs.getString("full_name"));
                    txtDob.setText(Utils.formatDate(rs.getDate("dob")));
                    txtEmail.setText(nullToEmpty(rs.getString("email")));
                    txtPhone.setText(nullToEmpty(rs.getString("phone")));
                    txtIssued.setText(Utils.formatDate(rs.getDate("card_issued")));
                    txtExpiry.setText(Utils.formatDate(rs.getDate("card_expiry")));
                    Utils.selectComboId(cboType, rs.getInt("type_id"));
                    Utils.selectComboCode(cboGender, rs.getString("gender"));
                    Utils.selectComboCode(cboStatus, rs.getString("status"));

                    Integer classId = (Integer) rs.getObject("class_id");
                    Integer facultyId = (Integer) rs.getObject("faculty_id");
                    Utils.selectComboId(cboClass, classId);          // selecting the class also fills in its faculty
                    if (facultyId != null || classId == null) {
                        Utils.selectComboId(cboFaculty, facultyId);
                    }
                }
            } finally {
                c.close();
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    /** Validates every field. Shows a message and returns false if something's wrong. */
    private boolean checkForm() {
        String cardNo = getCardNo();
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();

        if (!cardNo.matches("[A-Z0-9]{3,20}")) {
            return fail(txtCardNo, "Mã thẻ gồm 3-20 chữ cái hoặc chữ số, không dấu, không khoảng trắng.");
        }
        if (getFullName().isEmpty()) {
            return fail(txtFullName, "Vui lòng nhập họ tên.");
        }
        if (!phone.isEmpty() && !phone.matches("0[0-9]{9}")) {
            return fail(txtPhone, "Số điện thoại phải gồm 10 chữ số và bắt đầu bằng số 0.");
        }
        if (!email.isEmpty() && !email.matches("[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+")) {
            return fail(txtEmail, "Email không hợp lệ.");
        }

        LocalDate dob, issued, expiry;
        try {
            dob = Utils.parseDate(txtDob.getText());
        } catch (DateTimeParseException e) {
            return fail(txtDob, "Ngày sinh không đúng dạng dd/MM/yyyy.");
        }
        try {
            issued = Utils.parseDate(txtIssued.getText());
            expiry = Utils.parseDate(txtExpiry.getText());
        } catch (DateTimeParseException e) {
            return fail(txtIssued, "Ngày cấp thẻ và hạn thẻ phải đúng dạng dd/MM/yyyy.");
        }
        if (dob != null && dob.isAfter(LocalDate.now().minusYears(10))) {
            return fail(txtDob, "Ngày sinh không hợp lý (độc giả phải từ 10 tuổi trở lên).");
        }
        if (issued == null || expiry == null) {
            return fail(txtIssued, "Vui lòng nhập ngày cấp thẻ và hạn thẻ.");
        }
        if (!expiry.isAfter(issued)) {
            return fail(txtExpiry, "Hạn thẻ phải sau ngày cấp thẻ.");
        }
        if (cboType.getItemCount() == 0) {
            return fail(cboType, "Chưa có loại độc giả. Hãy thêm dữ liệu vào bảng reader_types.");
        }
        if (Utils.getComboId(cboClass) == null && Utils.getComboId(cboFaculty) == null) {
            return fail(cboFaculty, "Vui lòng chọn lớp (sinh viên) hoặc khoa (giảng viên).");
        }
        return true;
    }

    private boolean fail(javax.swing.JComponent field, String message) {
        Utils.showWarning(this, message);
        field.requestFocus();
        return false;
    }

    private void clearForm() {
        selectedId = -1;
        txtCardNo.setText("");
        txtFullName.setText("");
        txtDob.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        txtIssued.setText(Utils.formatDate(LocalDate.now()));
        txtExpiry.setText(Utils.formatDate(LocalDate.now().plusYears(4)));   // cards are valid for 4 years
        if (cboType.getItemCount() > 0) cboType.setSelectedIndex(0);
        if (cboClass.getItemCount() > 0) cboClass.setSelectedIndex(0);
        if (cboFaculty.getItemCount() > 0) cboFaculty.setSelectedIndex(0);
        cboGender.setSelectedIndex(0);
        cboStatus.setSelectedIndex(0);
        txtCardNo.requestFocus();
    }

