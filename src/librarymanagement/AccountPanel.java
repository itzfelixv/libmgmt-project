    private void loadAccounts() {
        String sql = "SELECT account_id AS 'ID', username AS 'Tên đăng nhập', full_name AS 'Họ tên', "
                + "email AS 'Email', phone AS 'Điện thoại', "
                + "CASE role WHEN 'ADMIN' THEN 'Quản trị viên' ELSE 'Thủ thư' END AS 'Vai trò', "
                + "CASE WHEN is_active THEN 'Hoạt động' ELSE 'Đã khóa' END AS 'Trạng thái', "
                + "DATE_FORMAT(last_login, '%d/%m/%Y %H:%i') AS 'Đăng nhập lần cuối' "
                + "FROM accounts ORDER BY username";
        try {
            Utils.loadTable(tblAccounts, sql);
            Utils.hideColumn(tblAccounts, 0);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void showSelectedAccount() {
        int id = Utils.getSelectedId(tblAccounts);
        if (id == -1) {
            return;
        }
        try {
            Connection c = DBConnection.getConn();
            try {
                PreparedStatement ps = c.prepareStatement("SELECT * FROM accounts WHERE account_id = ?");
                ps.setInt(1, id);
                ResultSet rs = ps.executeQuery();
                if (rs.next()) {
                    selectedId = id;
                    txtUsername.setText(rs.getString("username"));
                    txtFullName.setText(rs.getString("full_name"));
                    txtEmail.setText(rs.getString("email") == null ? "" : rs.getString("email"));
                    txtPhone.setText(rs.getString("phone") == null ? "" : rs.getString("phone"));
                    Utils.selectComboCode(cboRole, rs.getString("role"));
                    chkActive.setSelected(rs.getBoolean("is_active"));
                }
            } finally {
                c.close();
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private boolean checkForm() {
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();
        if (!getUsername().matches("[a-z0-9_.]{3,50}")) {
            return fail(txtUsername, "Tên đăng nhập gồm 3-50 chữ thường không dấu, chữ số, dấu . hoặc _.");
        }
        if (txtFullName.getText().trim().isEmpty()) {
            return fail(txtFullName, "Vui lòng nhập họ tên.");
        }
        if (!phone.isEmpty() && !phone.matches("0[0-9]{9}")) {
            return fail(txtPhone, "Số điện thoại phải gồm 10 chữ số và bắt đầu bằng số 0.");
        }
        if (!email.isEmpty() && !email.matches("[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+")) {
            return fail(txtEmail, "Email không hợp lệ.");
        }
        return true;
    }

    private boolean fail(javax.swing.JComponent field, String message) {
        Utils.showWarning(this, message);
        field.requestFocus();
        return false;
    }

    private void clearForm() {
        selectedId = -1;
        txtUsername.setText("");
        txtFullName.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        cboRole.setSelectedIndex(0);
        chkActive.setSelected(true);
    }

    private String getUsername() {
        return txtUsername.getText().trim().toLowerCase();
    }

    private static String emptyToNull(String text) {
        text = text.trim();
        return text.isEmpty() ? null : text;
    }

