    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!checkForm()) {
            return;
        }
        try {
            // New accounts start with the default password and have to change it the first time they log in
            DBConnection.update("INSERT INTO accounts (username, password_hash, full_name, email, phone, role, is_active, must_change_pw) "
                    + "VALUES (?, ?, ?, ?, ?, ?, ?, TRUE)",
                    getUsername(), BCrypt.hashpw(DEFAULT_PASSWORD, BCrypt.gensalt()), txtFullName.getText().trim(),
                    emptyToNull(txtEmail.getText()), emptyToNull(txtPhone.getText()),
                    Utils.getComboCode(cboRole), chkActive.isSelected());
            Utils.showInfo(this, "Đã tạo tài khoản " + getUsername() + ".\nMật khẩu: " + DEFAULT_PASSWORD
                    + " (người dùng sẽ phải đổi khi đăng nhập lần đầu).");
            loadAccounts();
            clearForm();
        } catch (SQLException ex) {
            if (ex.getErrorCode() == 1062) {
                Utils.showWarning(this, "Tên đăng nhập này đã có người dùng.");
            } else {
                Utils.showError(this, ex);
            }
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedId == -1) {
            Utils.showWarning(this, "Hãy chọn một tài khoản trong bảng để sửa.");
            return;
        }
        if (!checkForm()) {
            return;
        }
        // Don't let admins lock themselves out or take away their own admin role
        if (selectedId == LibraryManagement.SESSION.getAccountId()) {
            if (!chkActive.isSelected() || !"ADMIN".equals(Utils.getComboCode(cboRole))) {
                Utils.showWarning(this, "Bạn không thể tự khóa hoặc tự bỏ quyền quản trị của chính mình.");
                return;
            }
        }
        try {
            DBConnection.update("UPDATE accounts SET username = ?, full_name = ?, email = ?, phone = ?, role = ?, is_active = ? "
                    + "WHERE account_id = ?",
                    getUsername(), txtFullName.getText().trim(), emptyToNull(txtEmail.getText()),
                    emptyToNull(txtPhone.getText()), Utils.getComboCode(cboRole), chkActive.isSelected(), selectedId);
            int id = selectedId;
            loadAccounts();
            Utils.selectRowById(tblAccounts, id);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnResetPwActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetPwActionPerformed
        if (selectedId == -1) {
            Utils.showWarning(this, "Hãy chọn một tài khoản trong bảng.");
            return;
        }
        if (!Utils.confirm(this, "Đặt lại mật khẩu của " + getUsername() + " thành " + DEFAULT_PASSWORD + "?")) {
            return;
        }
        try {
            DBConnection.update("UPDATE accounts SET password_hash = ?, must_change_pw = TRUE WHERE account_id = ?",
                    BCrypt.hashpw(DEFAULT_PASSWORD, BCrypt.gensalt()), selectedId);
            Utils.showInfo(this, "Đã đặt lại mật khẩu. Người dùng sẽ phải đổi mật khẩu khi đăng nhập.");
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnResetPwActionPerformed

