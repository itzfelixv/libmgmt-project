    private void btnBorrowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrowActionPerformed
        if (readerId == -1) {
            Utils.showWarning(this, "Hãy nhập mã thẻ độc giả trước.");
            txtCardNo.requestFocus();
            return;
        }
        if (cart.getRowCount() == 0) {
            Utils.showWarning(this, "Chưa có sách nào trong phiếu mượn. Hãy quét mã vạch sách.");
            txtBarcode.requestFocus();
            return;
        }
        List<Integer> copyIds = new ArrayList<>();
        for (int i = 0; i < cart.getRowCount(); i++) {
            copyIds.add((Integer) cart.getValueAt(i, 0));
        }
        try {
            String loanCode = LoanService.borrow(readerId, copyIds, LibraryManagement.SESSION.getAccountId());
            Object dueDate = DBConnection.scalar("SELECT MAX(li.due_date) FROM loan_items li "
                    + "JOIN loans l ON l.loan_id = li.loan_id WHERE l.loan_code = ?", loanCode);
            Utils.showInfo(this, "Đã lập phiếu mượn " + loanCode + " gồm " + copyIds.size() + " cuốn.\n"
                    + "Hạn trả: " + Utils.formatDate((java.sql.Date) dueDate));
            cart.setRowCount(0);
            findReader();
        } catch (LoanService.LoanException ex) {
            Utils.showWarning(this, ex.getMessage());
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnBorrowActionPerformed

    /** Looks the reader up by card number and shows their info and current books. */
    private void findReader() {
        String cardNo = txtCardNo.getText().trim().toUpperCase();
        if (cardNo.isEmpty()) {
            return;
        }
        try {
            Connection c = DBConnection.getConn();
            try {
                PreparedStatement ps = c.prepareStatement(
                        "SELECT r.reader_id, r.full_name, r.status, r.card_expiry, t.name AS type_name, t.max_books, "
                        + "c.code AS class_code, COALESCE(f.name, cf.name) AS faculty_name "
                        + "FROM readers r JOIN reader_types t ON t.type_id = r.type_id "
                        + "LEFT JOIN classes c ON c.class_id = r.class_id "
                        + "LEFT JOIN faculties f ON f.faculty_id = r.faculty_id "
                        + "LEFT JOIN faculties cf ON cf.faculty_id = c.faculty_id "
                        + "WHERE r.card_no = ?");
                ps.setString(1, cardNo);
                ResultSet rs = ps.executeQuery();
                if (!rs.next()) {
                    clearReader();
                    Utils.showWarning(this, "Không tìm thấy độc giả có mã thẻ " + cardNo + ".");
                    txtCardNo.selectAll();
                    txtCardNo.requestFocus();
                    return;
                }
                readerId = rs.getInt("reader_id");
                LocalDate expiry = rs.getDate("card_expiry").toLocalDate();
                int maxBooks = rs.getInt("max_books");
                String status = rs.getString("status");

                lblReaderName.setText(rs.getString("full_name") + "  (" + cardNo + ")");
                String place = rs.getString("class_code") != null ? "Lớp " + rs.getString("class_code") : "";
                if (rs.getString("faculty_name") != null) {
                    place += (place.isEmpty() ? "" : " - ") + "Khoa " + rs.getString("faculty_name");
                }
                long debt = LoanService.getUnpaidFines(c, readerId);
                int onLoan = LoanService.countBooksOnLoan(c, readerId);
                lblReaderInfo.setText(rs.getString("type_name") + "   |   " + place
                        + "   |   Hạn thẻ: " + Utils.formatDate(expiry)
                        + "   |   Đang mượn: " + onLoan + "/" + maxBooks + " cuốn"
                        + "   |   Tiền phạt chưa nộp: " + Utils.formatMoney(debt));

                // Check whether they're allowed to borrow, and show the reason in red if not
                try {
                    LoanService.checkReaderCanBorrow(c, readerId, 1);
                    lblReaderStatus.setText("Được phép mượn sách.");
                    lblReaderStatus.setForeground(GREEN);
                } catch (LoanService.LoanException ex) {
                    lblReaderStatus.setText("KHÔNG ĐƯỢC MƯỢN: " + ex.getMessage().replace("\n", " "));
                    lblReaderStatus.setForeground(RED);
                }
            } finally {
                c.close();
            }
            loadLoans();
            txtBarcode.requestFocus();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void loadLoans() {
        String sql = "SELECT li.loan_item_id AS 'ID', bc.barcode AS 'Mã vạch', b.title AS 'Tên sách', "
                + "l.loan_code AS 'Phiếu mượn', DATE(l.loan_date) AS 'Ngày mượn', li.due_date AS 'Hạn trả', "
                + "li.renew_count AS 'Đã gia hạn', GREATEST(DATEDIFF(CURDATE(), li.due_date), 0) AS 'Số ngày quá hạn' "
                + "FROM loan_items li "
                + "JOIN loans l ON l.loan_id = li.loan_id "
                + "JOIN book_copies bc ON bc.copy_id = li.copy_id "
                + "JOIN books b ON b.book_id = bc.book_id "
                + "WHERE l.reader_id = ? AND li.return_date IS NULL ORDER BY li.due_date";
        try {
            Utils.loadTable(tblLoans, sql, readerId);
            Utils.hideColumn(tblLoans, 0);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void clearReader() {
        readerId = -1;
        lblReaderName.setText("-");
        lblReaderInfo.setText(" ");
        lblReaderStatus.setText(" ");
        tblLoans.setModel(new DefaultTableModel());
        if (cart != null) {
            cart.setRowCount(0);
        }
    }

    private void returnBook(int loanItemId) {
        String condition = Utils.getComboCode(cboCondition);
        if (!condition.equals("GOOD")) {
            if (!Utils.confirm(this, "Ghi nhận sách " + cboCondition.getSelectedItem() + "?")) {
                return;
            }
        }
        try {
            String message = LoanService.returnBook(loanItemId, condition, LibraryManagement.SESSION.getAccountId());
            Utils.showInfo(this, message);
            cboCondition.setSelectedIndex(0);
            findReader();
        } catch (LoanService.LoanException ex) {
            Utils.showWarning(this, ex.getMessage());
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    /** Looks up the scanned barcode and adds the book to the cart. Typing an ISBN works too. */
    private void addBookToCart() {
        String code = txtBarcode.getText().trim().toUpperCase();
        txtBarcode.setText("");
        txtBarcode.requestFocus();
        if (code.isEmpty()) {
            return;
        }
        if (readerId == -1) {
            Utils.showWarning(this, "Hãy nhập mã thẻ độc giả trước.");
            txtCardNo.requestFocus();
            return;
        }
        try {
            Connection c = DBConnection.getConn();
            try {
                PreparedStatement ps = c.prepareStatement(
                        "SELECT bc.copy_id, bc.barcode, bc.status, b.title FROM book_copies bc "
                        + "JOIN books b ON b.book_id = bc.book_id WHERE bc.barcode = ?");
                ps.setString(1, code);
                ResultSet rs = ps.executeQuery();
                if (!rs.next()) {
                    // Not a barcode, so try it as an ISBN and take the first copy that's on the shelf
                    ps = c.prepareStatement(
                            "SELECT bc.copy_id, bc.barcode, bc.status, b.title FROM book_copies bc "
                            + "JOIN books b ON b.book_id = bc.book_id "
                            + "WHERE b.isbn = ? AND b.is_deleted = 0 ORDER BY bc.status = 'AVAILABLE' DESC, bc.barcode LIMIT 1");
                    ps.setString(1, code.replace("-", ""));
                    rs = ps.executeQuery();
                    if (!rs.next()) {
                        Utils.showWarning(this, "Không tìm thấy sách có mã " + code + ".");
                        return;
                    }
                }
                int copyId = rs.getInt("copy_id");
                String barcode = rs.getString("barcode");
                String status = rs.getString("status");
                String title = rs.getString("title");

                for (int i = 0; i < cart.getRowCount(); i++) {
                    if (cart.getValueAt(i, 0).equals(copyId)) {
                        Utils.showWarning(this, "Sách này đã có trong phiếu.");
                        return;
                    }
                }
                if (status.equals("ON_LOAN")) {
                    Utils.showWarning(this, "Bản sách " + barcode + " đang được mượn, chưa trả.");
                    return;
                }
                if (!status.equals("AVAILABLE") && !status.equals("ON_HOLD")) {
                    Utils.showWarning(this, "Bản sách " + barcode + " không thể cho mượn (trạng thái: " + status + ").");
                    return;
                }
                cart.addRow(new Object[]{copyId, barcode, title});
            } finally {
                c.close();
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

