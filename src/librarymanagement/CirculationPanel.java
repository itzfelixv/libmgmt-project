    private void txtReturnBarcodeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtReturnBarcodeActionPerformed
        // Quick return: figure out who has this book, then return it
        String barcode = txtReturnBarcode.getText().trim().toUpperCase();
        if (barcode.isEmpty()) {
            return;
        }
        try {
            Connection c = DBConnection.getConn();
            int loanItemId = -1;
            String cardNo = null;
            try {
                PreparedStatement ps = c.prepareStatement(
                        "SELECT li.loan_item_id, r.card_no FROM loan_items li "
                        + "JOIN loans l ON l.loan_id = li.loan_id "
                        + "JOIN readers r ON r.reader_id = l.reader_id "
                        + "JOIN book_copies bc ON bc.copy_id = li.copy_id "
                        + "WHERE bc.barcode = ? AND li.return_date IS NULL");
                ps.setString(1, barcode);
                ResultSet rs = ps.executeQuery();
                if (rs.next()) {
                    loanItemId = rs.getInt(1);
                    cardNo = rs.getString(2);
                }
            } finally {
                c.close();
            }
            if (loanItemId == -1) {
                Utils.showWarning(this, "Không có ai đang mượn bản sách " + barcode + ".");
            } else {
                txtCardNo.setText(cardNo);
                findReader();
                Utils.selectRowById(tblLoans, loanItemId);
                returnBook(loanItemId);
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
        txtReturnBarcode.setText("");
        txtReturnBarcode.requestFocus();
    }//GEN-LAST:event_txtReturnBarcodeActionPerformed

