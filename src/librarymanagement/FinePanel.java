    private void btnPayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPayActionPerformed
        int fineId = Utils.getSelectedId(tblFines);
        if (fineId == -1) {
            Utils.showWarning(this, "Hãy chọn một khoản phạt trong bảng.");
            return;
        }
        try {
            String status = (String) DBConnection.scalar("SELECT status FROM fines WHERE fine_id = ?", fineId);
            if (!status.equals("UNPAID")) {
                Utils.showWarning(this, "Khoản phạt này đã được xử lý rồi.");
                return;
            }
            Object amount = Utils.getSelectedValue(tblFines, COL_AMOUNT);
            String name = (String) Utils.getSelectedValue(tblFines, 2);
            if (!Utils.confirm(this, "Thu " + Utils.formatMoney(((Number) amount).longValue()) + " của " + name + "?")) {
                return;
            }
            String receiptNo = "PT" + String.format("%06d", fineId);   // receipt number we give to the reader
            DBConnection.update("UPDATE fines SET status = 'PAID', paid_at = NOW(), handled_by = ?, receipt_no = ? "
                    + "WHERE fine_id = ?", LibraryManagement.SESSION.getAccountId(), receiptNo, fineId);
            Utils.showInfo(this, "Đã thu tiền. Số biên lai: " + receiptNo);
            loadFines();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnPayActionPerformed

    private void btnWaiveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnWaiveActionPerformed
        int fineId = Utils.getSelectedId(tblFines);
        if (fineId == -1) {
            Utils.showWarning(this, "Hãy chọn một khoản phạt trong bảng.");
            return;
        }
        String reason = JOptionPane.showInputDialog(this, "Lý do miễn phạt:", "Miễn phạt", JOptionPane.QUESTION_MESSAGE);
        if (reason == null) {
            return;   // they pressed Cancel
        }
        if (reason.trim().isEmpty()) {
            Utils.showWarning(this, "Phải ghi lý do miễn phạt.");
            return;
        }
        try {
            int rows = DBConnection.update("UPDATE fines SET status = 'WAIVED', paid_at = NOW(), handled_by = ?, note = ? "
                    + "WHERE fine_id = ? AND status = 'UNPAID'",
                    LibraryManagement.SESSION.getAccountId(), "Miễn phạt: " + reason.trim(), fineId);
            if (rows == 0) {
                Utils.showWarning(this, "Khoản phạt này đã được xử lý rồi.");
            }
            loadFines();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnWaiveActionPerformed

    private void loadFines() {
        String[] statuses = {"UNPAID", "PAID", "WAIVED"};
        int show = cboShow.getSelectedIndex();
        String where = "";
        if (show < 3) {
            where = "WHERE f.status = '" + statuses[show] + "' ";
        }
        String sql = "SELECT f.fine_id AS 'ID', r.card_no AS 'Mã thẻ', r.full_name AS 'Họ tên', "
                + "CASE f.fine_type WHEN 'OVERDUE' THEN 'Trả trễ' WHEN 'DAMAGED' THEN 'Hư hỏng sách' "
                + "  WHEN 'LOST' THEN 'Mất sách' ELSE 'Khác' END AS 'Loại', "
                + "b.title AS 'Tên sách', f.days_overdue AS 'Số ngày trễ', f.amount AS 'Số tiền', "
                + "CASE f.status WHEN 'UNPAID' THEN 'Chưa nộp' WHEN 'PAID' THEN 'Đã nộp' ELSE 'Đã miễn' END AS 'Trạng thái', "
                + "DATE(f.created_at) AS 'Ngày phạt', f.receipt_no AS 'Số biên lai', f.note AS 'Ghi chú' "
                + "FROM fines f JOIN readers r ON r.reader_id = f.reader_id "
                + "LEFT JOIN loan_items li ON li.loan_item_id = f.loan_item_id "
                + "LEFT JOIN book_copies bc ON bc.copy_id = li.copy_id "
                + "LEFT JOIN books b ON b.book_id = bc.book_id "
                + where
                + "ORDER BY f.created_at DESC";
        try {
            Utils.loadTable(tblFines, sql);
            Utils.hideColumn(tblFines, 0);
            search();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    /** Applies the search filter and adds up the amounts currently shown. */
    private void search() {
        Utils.filterTable(tblFines, txtSearch.getText());
        long total = 0;
        for (int i = 0; i < tblFines.getRowCount(); i++) {
            int modelRow = tblFines.convertRowIndexToModel(i);
            Object amount = tblFines.getModel().getValueAt(modelRow, COL_AMOUNT);
            if (amount != null) {
                total += ((Number) amount).longValue();
            }
        }
        lblTotal.setText(tblFines.getRowCount() + " khoản  -  Tổng: " + Utils.formatMoney(total));
    }

