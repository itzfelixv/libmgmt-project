    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String oldPassword = new String(txtOld.getPassword());
        String newPassword = new String(txtNew.getPassword());
        String confirm = new String(txtConfirm.getPassword());

        if (!newPassword.equals(confirm)) {
            Utils.showWarning(this, "Mật khẩu nhập lại không khớp.");
            txtConfirm.requestFocus();
            return;
        }

        try {
            // Session checks the old password and the length, then saves the new BCrypt hash
            LibraryManagement.SESSION.changePassword(oldPassword, newPassword);
            changed = true;
            Utils.showInfo(this, "Đổi mật khẩu thành công.");
            dispose();
        } catch (LoginException ex) {
            Utils.showWarning(this, ex.getMessage());
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

