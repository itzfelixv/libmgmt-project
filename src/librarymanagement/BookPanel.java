    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!checkForm()) {
            return;
        }
        int copies;
        try {
            copies = Integer.parseInt(txtNewCopies.getText().trim());
        } catch (NumberFormatException e) {
            copies = -1;
        }
        if (copies < 0 || copies > 100) {
            Utils.showWarning(this, "Số bản phải là số từ 0 đến 100.");
            txtNewCopies.requestFocus();
            return;
        }

        try {
            Connection c = DBConnection.getConn();
            try {
                c.setAutoCommit(false);   // Save the book, its authors and its copies in one go
                PreparedStatement ps = c.prepareStatement(
                        "INSERT INTO books (isbn, title, category_id, publisher_id, publish_year, price, is_reference) "
                        + "VALUES (?, ?, ?, ?, ?, ?, ?)", PreparedStatement.RETURN_GENERATED_KEYS);
                setBookParameters(ps);
                ps.executeUpdate();
                ResultSet keys = ps.getGeneratedKeys();
                keys.next();
                int bookId = keys.getInt(1);

                saveAuthors(c, bookId);
                addCopies(c, bookId, copies, "");
                c.commit();

                Utils.showInfo(this, "Đã thêm đầu sách \"" + txtTitle.getText().trim() + "\" với " + copies + " bản.");
                loadBooks();
                Utils.selectRowById(tblBooks, bookId);
            } catch (SQLException ex) {
                c.rollback();
                throw ex;
            } finally {
                c.close();
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedBookId == -1) {
            Utils.showWarning(this, "Hãy chọn một đầu sách trong bảng để sửa.");
            return;
        }
        if (!checkForm()) {
            return;
        }
        try {
            Connection c = DBConnection.getConn();
            try {
                c.setAutoCommit(false);
                PreparedStatement ps = c.prepareStatement(
                        "UPDATE books SET isbn=?, title=?, category_id=?, publisher_id=?, publish_year=?, price=?, is_reference=? "
                        + "WHERE book_id=?");
                setBookParameters(ps);
                ps.setInt(8, selectedBookId);
                ps.executeUpdate();
                saveAuthors(c, selectedBookId);
                c.commit();
            } catch (SQLException ex) {
                c.rollback();
                throw ex;
            } finally {
                c.close();
            }
            Utils.showInfo(this, "Đã cập nhật đầu sách.");
            int id = selectedBookId;
            loadBooks();
            Utils.selectRowById(tblBooks, id);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedBookId == -1) {
            Utils.showWarning(this, "Hãy chọn một đầu sách trong bảng để xóa.");
            return;
        }
        try {
            Object busy = DBConnection.scalar("SELECT COUNT(*) FROM book_copies WHERE book_id = ? "
                    + "AND status IN ('ON_LOAN', 'ON_HOLD')", selectedBookId);
            if (((Number) busy).intValue() > 0) {
                Utils.showWarning(this, "Không thể xóa: có " + busy + " bản sách đang được mượn hoặc giữ cho người đặt trước.");
                return;
            }
            if (!Utils.confirm(this, "Xóa đầu sách \"" + txtTitle.getText().trim() + "\"?\n"
                    + "(Lịch sử mượn vẫn được giữ lại, các bản sách sẽ chuyển sang \"Thanh lý\".)")) {
                return;
            }
            // We don't really delete it, just hide it, so old loan records still make sense
            DBConnection.update("UPDATE books SET is_deleted = 1 WHERE book_id = ?", selectedBookId);
            DBConnection.update("UPDATE book_copies SET status = 'WITHDRAWN' WHERE book_id = ?", selectedBookId);
            loadBooks();
            clearForm();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

