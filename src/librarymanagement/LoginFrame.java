    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());

        try {
            LibraryManagement.SESSION.login(username, password);
        } catch (LoginException ex) {
            // wrong password, locked account, etc.
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Đăng nhập thất bại", JOptionPane.WARNING_MESSAGE);
            txtPassword.setText("");
            txtPassword.requestFocus();
            return;
        } catch (SQLException ex) {
            Utils.showError(this, ex);
            return;
        }

        // After an admin reset, the user has to pick a new password before going in
        if (LibraryManagement.SESSION.mustChangePassword()) {
            ChangePwdDialog dialog = new ChangePwdDialog(this, true);
            dialog.setVisible(true);
            if (!dialog.isChanged()) {
                LibraryManagement.SESSION.logout();
                return;
            }
        }

        new MainFrame().setVisible(true);
        dispose();
    }//GEN-LAST:event_btnLoginActionPerformed

