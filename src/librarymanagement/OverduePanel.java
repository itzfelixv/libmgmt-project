    private void loadLoans() {
        int show = cboShow.getSelectedIndex();
        String where;
        where = switch (show) {
            case 1 -> "WHERE v.days_overdue > 0 ";
            case 2 -> "WHERE v.days_overdue > " + Utils.getSettingInt("OVERDUE_REPORT_DAYS", 30) + " ";
            default -> "";
        };
        // v_open_loans is a view in the database that already joins loans, readers, classes and books
        String sql = "SELECT v.loan_item_id AS 'ID', v.card_no AS 'Mã thẻ', v.full_name AS 'Họ tên', "
                + "v.class_code AS 'Lớp', v.faculty_name AS 'Khoa', r.phone AS 'Điện thoại', "
                + "v.barcode AS 'Mã vạch', v.title AS 'Tên sách', DATE(v.loan_date) AS 'Ngày mượn', "
                + "v.due_date AS 'Hạn trả', v.days_overdue AS 'Số ngày quá hạn' "
                + "FROM v_open_loans v JOIN readers r ON r.reader_id = v.reader_id "
                + where
                + "ORDER BY v.faculty_name, v.class_code, v.full_name";
        try {
            Utils.loadTable(tblLoans, sql);
            Utils.hideColumn(tblLoans, 0);
            search();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void search() {
        Utils.filterTable(tblLoans, txtSearch.getText());
        lblCount.setText(tblLoans.getRowCount() + " dòng");
    }

