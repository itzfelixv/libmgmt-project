    /** Runs when you pick another list: shows the right fields and reloads the table. */
    private void changeList() {
        int type = cboType.getSelectedIndex();

        boolean hasCode = (type == FACULTY || type == COHORT || type == CLASS);
        boolean hasName = (type != COHORT);
        boolean isClass = (type == CLASS);
        boolean isCohort = (type == COHORT);

        lblCode.setVisible(hasCode);
        txtCode.setVisible(hasCode);
        lblName.setVisible(hasName);
        txtName.setVisible(hasName);
        lblFaculty.setVisible(isClass);
        cboFaculty.setVisible(isClass);
        lblCohort.setVisible(isClass);
        cboCohort.setVisible(isClass);
        lblStartYear.setVisible(isCohort);
        txtStartYear.setVisible(isCohort);
        lblEndYear.setVisible(isCohort);
        txtEndYear.setVisible(isCohort);

        if (isClass) {
            try {
                Utils.fillCombo(cboFaculty, "SELECT faculty_id, name FROM faculties ORDER BY name", null);
                Utils.fillCombo(cboCohort, "SELECT cohort_id, code FROM cohorts ORDER BY start_year DESC", null);
            } catch (SQLException ex) {
                Utils.showError(this, ex);
            }
        }
        txtSearch.setText("");
        loadItems();
        clearForm();
        revalidate();
        repaint();
    }

    private void loadItems() {
        int type = cboType.getSelectedIndex();
        String sql;
        sql = switch (type) {
            case FACULTY -> "SELECT faculty_id AS 'ID', code AS 'Mã khoa', name AS 'Tên khoa', "
                + "(SELECT COUNT(*) FROM classes c WHERE c.faculty_id = f.faculty_id) AS 'Số lớp' "
                + "FROM faculties f ORDER BY name";
            case COHORT -> "SELECT cohort_id AS 'ID', code AS 'Mã khóa', start_year AS 'Năm bắt đầu', end_year AS 'Năm kết thúc' "
                + "FROM cohorts ORDER BY start_year DESC";
            case CLASS -> "SELECT c.class_id AS 'ID', c.code AS 'Mã lớp', c.name AS 'Tên lớp', f.name AS 'Khoa', k.code AS 'Khóa', "
                + "(SELECT COUNT(*) FROM readers r WHERE r.class_id = c.class_id) AS 'Số độc giả' "
                + "FROM classes c JOIN faculties f ON f.faculty_id = c.faculty_id "
                + "JOIN cohorts k ON k.cohort_id = c.cohort_id ORDER BY c.code";
            case CATEGORY -> "SELECT category_id AS 'ID', name AS 'Thể loại', "
                + "(SELECT COUNT(*) FROM books b WHERE b.category_id = c.category_id AND b.is_deleted = 0) AS 'Số đầu sách' "
                + "FROM categories c ORDER BY name";
            case PUBLISHER -> "SELECT publisher_id AS 'ID', name AS 'Nhà xuất bản', "
                + "(SELECT COUNT(*) FROM books b WHERE b.publisher_id = p.publisher_id AND b.is_deleted = 0) AS 'Số đầu sách' "
                + "FROM publishers p ORDER BY name";
            default -> "SELECT author_id AS 'ID', name AS 'Tác giả', "
                + "(SELECT COUNT(*) FROM book_authors ba WHERE ba.author_id = a.author_id) AS 'Số đầu sách' "
                + "FROM authors a ORDER BY name";
        };
        try {
            Utils.loadTable(tblItems, sql);
            Utils.hideColumn(tblItems, 0);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private void showSelectedItem() {
        int id = Utils.getSelectedId(tblItems);
        if (id == -1) {
            return;
        }
        selectedId = id;
        int type = cboType.getSelectedIndex();
        try {
            Connection c = DBConnection.getConn();
            try {
                PreparedStatement ps;
                ps = switch (type) {
                    case FACULTY -> c.prepareStatement("SELECT code, name FROM faculties WHERE faculty_id = ?");
                    case COHORT -> c.prepareStatement("SELECT code, start_year, end_year FROM cohorts WHERE cohort_id = ?");
                    case CLASS -> c.prepareStatement("SELECT code, name, faculty_id, cohort_id FROM classes WHERE class_id = ?");
                    case CATEGORY -> c.prepareStatement("SELECT name FROM categories WHERE category_id = ?");
                    case PUBLISHER -> c.prepareStatement("SELECT name FROM publishers WHERE publisher_id = ?");
                    default -> c.prepareStatement("SELECT name FROM authors WHERE author_id = ?");
                };
                ps.setInt(1, id);
                ResultSet rs = ps.executeQuery();
                if (!rs.next()) {
                    return;
                }
                switch (type) {
                    case FACULTY -> {
                        txtCode.setText(rs.getString("code"));
                        txtName.setText(rs.getString("name"));
                    }
                    case COHORT -> {
                        txtCode.setText(rs.getString("code"));
                        txtStartYear.setText(rs.getString("start_year"));
                        txtEndYear.setText(rs.getString("end_year"));
                    }
                    case CLASS -> {
                        txtCode.setText(rs.getString("code"));
                        txtName.setText(rs.getString("name") == null ? "" : rs.getString("name"));
                        Utils.selectComboId(cboFaculty, rs.getInt("faculty_id"));
                        Utils.selectComboId(cboCohort, rs.getInt("cohort_id"));
                    }
                    default -> txtName.setText(rs.getString("name"));
                }
            } finally {
                c.close();
            }
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }

    private boolean checkForm() {
        int type = cboType.getSelectedIndex();
        if (txtCode.isVisible() && !getCode().matches("[A-Z0-9_-]{1,20}")) {
            return fail(txtCode, "Mã gồm 1-20 chữ cái không dấu, chữ số, dấu - hoặc _.");
        }
        if (txtName.isVisible() && type != CLASS && getItemName().isEmpty()) {
            return fail(txtName, "Vui lòng nhập tên.");
        }
        if (type == CLASS && (cboFaculty.getItemCount() == 0 || cboCohort.getItemCount() == 0)) {
            return fail(cboFaculty, "Hãy tạo Khoa và Khóa học trước khi tạo Lớp.");
        }
        if (type == COHORT) {
            if (getStartYear() == null || getEndYear() == null) {
                return fail(txtStartYear, "Năm bắt đầu và năm kết thúc phải là số có 4 chữ số.");
            }
            if (getEndYear() <= getStartYear()) {
                return fail(txtEndYear, "Năm kết thúc phải lớn hơn năm bắt đầu.");
            }
        }
        return true;
    }

    private boolean fail(javax.swing.JComponent field, String message) {
        Utils.showWarning(this, message);
        field.requestFocus();
        return false;
    }

    private void clearForm() {
        selectedId = -1;
        txtCode.setText("");
        txtName.setText("");
        txtStartYear.setText("");
        txtEndYear.setText("");
    }

    private String getCode() {
        return txtCode.getText().trim().toUpperCase();
    }

    private String getItemName() {
        return txtName.getText().trim();
    }

    private Integer getStartYear() {
        return toYear(txtStartYear.getText());
    }

    private Integer getEndYear() {
        return toYear(txtEndYear.getText());
    }

    private static Integer toYear(String text) {
        text = text.trim();
        if (!text.matches("[0-9]{4}")) {
            return null;
        }
        return Integer.valueOf(text);
    }

