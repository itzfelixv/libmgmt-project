    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!checkForm()) {
            return;
        }
        int type = cboType.getSelectedIndex();
        try {
            switch (type) {
                case FACULTY -> DBConnection.update("INSERT INTO faculties (code, name) VALUES (?, ?)", getCode(), getItemName());
                case COHORT -> DBConnection.update("INSERT INTO cohorts (code, start_year, end_year) VALUES (?, ?, ?)",
                            getCode(), getStartYear(), getEndYear());
                case CLASS -> DBConnection.update("INSERT INTO classes (code, name, faculty_id, cohort_id) VALUES (?, ?, ?, ?)",
                            getCode(), getItemName(), Utils.getComboId(cboFaculty), Utils.getComboId(cboCohort));
                case CATEGORY -> DBConnection.update("INSERT INTO categories (name) VALUES (?)", getItemName());
                case PUBLISHER -> DBConnection.update("INSERT INTO publishers (name) VALUES (?)", getItemName());
                default -> DBConnection.update("INSERT INTO authors (name) VALUES (?)", getItemName());
            }
            loadItems();
            clearForm();
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedId == -1) {
            Utils.showWarning(this, "Hãy chọn một dòng trong bảng để sửa.");
            return;
        }
        if (!checkForm()) {
            return;
        }
        int type = cboType.getSelectedIndex();
        try {
            switch (type) {
                case FACULTY -> DBConnection.update("UPDATE faculties SET code = ?, name = ? WHERE faculty_id = ?", getCode(), getItemName(), selectedId);
                case COHORT -> DBConnection.update("UPDATE cohorts SET code = ?, start_year = ?, end_year = ? WHERE cohort_id = ?",
                            getCode(), getStartYear(), getEndYear(), selectedId);
                case CLASS -> DBConnection.update("UPDATE classes SET code = ?, name = ?, faculty_id = ?, cohort_id = ? WHERE class_id = ?",
                            getCode(), getItemName(), Utils.getComboId(cboFaculty), Utils.getComboId(cboCohort), selectedId);
                case CATEGORY -> DBConnection.update("UPDATE categories SET name = ? WHERE category_id = ?", getItemName(), selectedId);
                case PUBLISHER -> DBConnection.update("UPDATE publishers SET name = ? WHERE publisher_id = ?", getItemName(), selectedId);
                default -> DBConnection.update("UPDATE authors SET name = ? WHERE author_id = ?", getItemName(), selectedId);
            }
            int id = selectedId;
            loadItems();
            Utils.selectRowById(tblItems, id);
        } catch (SQLException ex) {
            Utils.showError(this, ex);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedId == -1) {
            Utils.showWarning(this, "Hãy chọn một dòng trong bảng để xóa.");
            return;
        }
        if (!Utils.confirm(this, "Xóa \"" + Utils.getSelectedValue(tblItems, 1) + "\"?")) {
            return;
        }
        String[] tables = {"faculties", "cohorts", "classes", "categories", "publishers", "authors"};
        String[] idColumns = {"faculty_id", "cohort_id", "class_id", "category_id", "publisher_id", "author_id"};
        int type = cboType.getSelectedIndex();
        try {
            DBConnection.update("DELETE FROM " + tables[type] + " WHERE " + idColumns[type] + " = ?", selectedId);
            loadItems();
            clearForm();
        } catch (SQLException ex) {
            if (ex.getErrorCode() == 1451) {
                Utils.showWarning(this, "Không thể xóa vì mục này đang được dùng (có độc giả, lớp hoặc sách thuộc mục này).");
            } else {
                Utils.showError(this, ex);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

