    /** Switches to the tab with this title if it's already open. Returns true if it was. */
    private boolean selectTab(String title) {
        for (int i = 0; i < tabs.getTabCount(); i++) {
            if (tabs.getTitleAt(i).equals(title)) {
                tabs.setSelectedIndex(i);
                return true;
            }
        }
        return false;
    }

    /** Opens a screen as a new tab with a small "x" to close it. */
    private void addTab(String title, final JPanel panel) {
        tabs.addTab(title, panel);
        int index = tabs.indexOfComponent(panel);

        JPanel header = new JPanel(new FlowLayout(FlowLayout.LEFT, 4, 0));
        header.setOpaque(false);
        header.add(new JLabel(title));

        JButton btnClose = new JButton("x");
        btnClose.setBorderPainted(false);
        btnClose.setContentAreaFilled(false);
        btnClose.setFocusable(false);
        btnClose.setToolTipText("Đóng");
        btnClose.addActionListener(new ActionListener() {
            public void actionPerformed(ActionEvent e) {
                tabs.remove(panel);
            }
        });
        header.add(btnClose);

        tabs.setTabComponentAt(index, header);
        tabs.setSelectedIndex(index);
    }

    /** The first tab: a welcome message and a few quick numbers. */
    private void openHomeTab() {
        String books = "?", readers = "?", onLoan = "?", overdue = "?";
        try {
            books = String.valueOf(DBConnection.scalar("SELECT COUNT(*) FROM book_copies WHERE status <> 'WITHDRAWN'"));
            readers = String.valueOf(DBConnection.scalar("SELECT COUNT(*) FROM readers WHERE status = 'ACTIVE'"));
            onLoan = String.valueOf(DBConnection.scalar("SELECT COUNT(*) FROM loan_items WHERE return_date IS NULL"));
            overdue = String.valueOf(DBConnection.scalar(
                    "SELECT COUNT(*) FROM loan_items WHERE return_date IS NULL AND due_date < CURDATE()"));
        } catch (SQLException ex) {
            // just show "?" if the database is having problems
        }

        JLabel welcome = new JLabel("<html><div style='text-align:center'>"
                + "<h1>Xin chào, " + LibraryManagement.SESSION.getFullName() + "</h1>"
                + "<p>Bản sách trong thư viện: <b>" + books + "</b> &nbsp;|&nbsp; "
                + "Độc giả đang hoạt động: <b>" + readers + "</b></p>"
                + "<p>Sách đang được mượn: <b>" + onLoan + "</b> &nbsp;|&nbsp; "
                + "<span style='color:red'>Sách quá hạn: <b>" + overdue + "</b></span></p>"
                + "<br><p>F2: Độc giả &nbsp; F3: Sách &nbsp; F5: Mượn / Trả &nbsp; Ctrl+L: Đăng xuất</p>"
                + "</div></html>", SwingConstants.CENTER);
        welcome.setFont(welcome.getFont().deriveFont(Font.PLAIN, 15f));
        tabs.addTab("Trang chủ", welcome);
    }

    /** Updates the clock in the status bar every second. */
    private void startClock() {
        final DateTimeFormatter format = DateTimeFormatter.ofPattern("HH:mm:ss - dd/MM/yyyy");
        clockTimer = new Timer(1000, new ActionListener() {
            public void actionPerformed(ActionEvent e) {
                lblClock.setText(LocalDateTime.now().format(format));
            }
        });
        clockTimer.setInitialDelay(0);
        clockTimer.start();
    }

    private void exitProgram() {
        if (Utils.confirm(this, "Thoát chương trình?")) {
            System.exit(0);
        }
    }

